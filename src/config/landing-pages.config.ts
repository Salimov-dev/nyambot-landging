export type IBlockIcon = (typeof BLOCK_ICON)[keyof typeof BLOCK_ICON];

export type ILandingPageBlock = {
  icon: IBlockIcon;
  title: string;
  text: string;
  /** Пункты под текстом — границы возможности, о которых ресторатор
   *  спросит первым делом. */
  points?: string[];
  /** Ссылка под текстом карточки — например, на бесплатный разбор. */
  link?: { label: string; href: string };
  /** Карточка во всю ширину сетки. Ставится последней карточке при нечётном
   *  их числе — иначе на десктопе она стоит одна рядом с пустой ячейкой. */
  wide?: boolean;
};

export type ILandingPageQuestion = {
  question: string;
  answer: string;
};

export type ILandingPageContent = {
  /** Адрес страницы от корня сайта — он же канонический. */
  path: string;
  metaTitle: string;
  metaDescription: string;
  /** Надзаголовочная пилюля: называет тему страницы одним словосочетанием. */
  label: string;
  heading: string;
  lead: string;
  blocks: ILandingPageBlock[];
  /** Чего делать НЕ придётся — подача УТП через снятые требования.
   *  Может не быть: на странице-справочнике снимать нечего. */
  notNeeded?: string[];
  guide: { href: string; label: string };
  /** Вопросы-ответы. Уходят и в разметку FAQPage — за расширенным сниппетом. */
  faq: ILandingPageQuestion[];
  /** Показать под кнопками общий QR-код демо — у страниц про общий QR-код и
   *  брендирование (у демо лого в центре кода). */
  demoQr?: boolean;
};

