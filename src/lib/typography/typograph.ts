import { noWidow } from "./no-widow";

const NBSP = " ";

/**
 * Тире не открывает строку: пробел ПЕРЕД « — » — неразрывный (Руслан
 * 16.10.2026: «Запуск / — бесплатно» с тире в начале строки читается плохо).
 * Тексты словарей держат неразрывный пробел сами — эта склейка для текстов
 * конфигов, где невидимый символ в исходнике легко потерять.
 */
export const glueDash = (text: string): string =>
  text.replace(/ (?=— )/gu, NBSP);

/** Текст на экране: тире не с новой строки, последнее слово не одно. */
export const typograph = (text: string): string => noWidow(glueDash(text));
