/**
 * ОБЩИЕ ПРАВИЛА ТЕЛЕФОНА — единственный источник.
 *
 * План гостевого режима, Ф1.3 (находка Н4 разведки Ф0). Класс решения Р37
 * плана-дирижёра: централизуются ПРАВИЛА, а не их применение.
 *
 * ## Зачем
 *
 * Правило «8 → +7» было написано в девяти местах четырёх проектов, и копии
 * разошлись. Пока номер собирал только онбординг РФ-мессенджеров, это не
 * всплывало. Гостевой режим делает телефон КЛЮЧОМ ИДЕНТИЧНОСТИ на оформлении:
 * один и тот же человек, записанный двумя разными строками, получит два
 * профиля, два баланса баллов и чужую историю заказов.
 *
 * Расхождение не гипотетическое: в прод-производной базе уже лежит украинский
 * `+380506626445`, а нормализация СРМ превращала его в `+73805066244` —
 * то есть в номер другого человека.
 *
 * ## Два разных вопроса, которые нельзя путать
 *
 * 1. **«Один ли это номер?»** — `normalizePhone`. Ключ идентичности, пишется в
 *    БД, по нему `@unique`. Страну НЕ угадывает: чего не знаем, того не
 *    выдумываем. Эталон — серверный `normalize-phone.util.ts`, перенесён
 *    ДОСЛОВНО (урок §10 дирижёра: первая версия общего денежного модуля была
 *    написана «как правильнее» и разошлась с продуктом сразу в трёх местах).
 * 2. **«Что показать и как принять ввод?»** — остальные функции. Поле с маской
 *    «+7 …» вправе достроить код страны, потому что сама маска это и обещает.
 *
 * ## Что сюда НЕ переезжает
 *
 * Вид показа. «+7 900 123 45 67» у мини-аппа и «+7 (900) 123-45-67» у СРМ —
 * это оформление, оно остаётся своим у каждого клиента. Но решение «этот номер
 * российский» и «этот трогать нельзя» принимается здесь, а не в каждой таблице.
 */

/** Код страны России в каноничной записи. */
const RU_COUNTRY_CODE = "7";
/** Российский номер без кода страны — ровно столько цифр. */
const RU_SUBSCRIBER_LENGTH = 10;
/** Российский номер целиком, с кодом страны. */
const RU_FULL_LENGTH = RU_SUBSCRIBER_LENGTH + 1;

/** Оставляет только цифры: «+7 (931) 530-25-07» → «79315302507». */
export function phoneDigits(input: string | null | undefined): string {
  if (!input) return "";
  return input.replace(/\D/g, "");
}

/**
 * КЛЮЧ ИДЕНТИЧНОСТИ. Приводит номер к каноничному `+<цифры>`.
 *
 * 🔴 Страну не угадывает. Десять цифр остаются десятью цифрами: «9315302507»
 * даёт «+9315302507», а не «+79315302507». Достраивать код страны вправе только
 * поле ввода, которое этот код показывает — `normalizeRuPhoneInput`.
 *
 * Эталон: `main-server/server/utils/phone/normalize-phone.util.ts`, дословно.
 */
export function normalizePhone(input: string | null | undefined): string {
  const trimmed = input?.trim();
  if (!trimmed) return "";

  const digitsOnly = phoneDigits(trimmed);
  if (!digitsOnly) return "";

  // Российский формат: 8XXXXXXXXXX → 7XXXXXXXXXX
  const normalized =
    digitsOnly.length === RU_FULL_LENGTH && digitsOnly.startsWith("8")
      ? `${RU_COUNTRY_CODE}${digitsOnly.slice(1)}`
      : digitsOnly;

  return `+${normalized}`;
}

/** Канон российского номера: `+7` и ровно десять цифр после. */
const RU_CANONICAL = /^\+7\d{10}$/;

/** Номер в каноне и есть российский. */
export function isRussianPhone(input: string | null | undefined): boolean {
  return RU_CANONICAL.test(normalizePhone(input));
}

/**
 * Номер заведомо НЕ российский — эвристика для показа и полей ввода.
 *
 * Истинна, когда цифр набрано не меньше, чем в полном российском номере, и
 * первая из них не «7» и не «8». Такой номер нельзя ни форматировать РФ-маской,
 * ни дописывать ему код страны: получится другой номер.
 *
 * ⚖️ Это правило показа, а не резолвер страны. Ключ идентичности
 * (`normalizePhone`) никаких стран не различает вовсе.
 */
export function isForeignPhone(input: string | null | undefined): boolean {
  const digits = phoneDigits(input);
  if (digits.length < RU_FULL_LENGTH) return false;
  return !digits.startsWith("7") && !digits.startsWith("8");
}

/**
 * Цифры российского номера БЕЗ кода страны — до десяти штук.
 * Для полей ввода с маской «+7 …»: маска сама рисует код, ей нужен остаток.
 *
 * Работает и на недобранном номере — «7900» даёт «900», это ввод в процессе.
 */
export function ruSubscriberDigits(input: string | null | undefined): string {
  return ruDigitsAfterCountryCode(input).slice(0, RU_SUBSCRIBER_LENGTH);
}

/**
 * Сколько цифр набрано сверх кода страны — для валидации поля ввода.
 *
 * От `ruSubscriberDigits` отличается тем, что НЕ режет перебор: маске лишние
 * цифры не нужны, а валидатору нужны — перебор такая же ошибка ввода, как
 * недобор, и её надо показать.
 */
export function ruDigitsAfterCountryCode(
  input: string | null | undefined,
): string {
  const digits = phoneDigits(input);
  return digits.startsWith("7") || digits.startsWith("8")
    ? digits.slice(1)
    : digits;
}

/**
 * Значение поля ввода российского номера → канон для отправки на сервер.
 *
 * Отличается от `normalizePhone` двумя вещами, и обе — про поле, а не про ключ:
 * десять цифр без кода страны трактуются как российский номер (поле показывает
 * «+7»), а одна цифра номером не считается вовсе — это недобранный ввод, а не
 * номер `+5`. Всё остальное, включая нероссийские номера, уходит в
 * `normalizePhone` как есть: калечить их нельзя.
 */
export function normalizeRuPhoneInput(
  input: string | null | undefined,
): string {
  const digits = phoneDigits(input);
  // Одна цифра — это ввод в процессе, а не номер.
  if (digits.length < 2) return "";

  if (isForeignPhone(digits)) return normalizePhone(digits);

  if (digits.length === RU_SUBSCRIBER_LENGTH) {
    return `+${RU_COUNTRY_CODE}${digits}`;
  }

  return normalizePhone(digits);
}
