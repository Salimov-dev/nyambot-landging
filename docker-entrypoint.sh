#!/bin/sh
# Файлы прошлых сборок — рядом с текущей.
#
# Имена скриптов Next меняются с каждой сборкой, а старые после выката пропадали.
# Кто загрузил HTML до выката, а скрипты запросил после, получал 404 и экран
# ошибки. Так робот Яндекса, который выполняет JS спустя часы, проиндексировал
# главную как «Попробовать снова / Перезагрузить страницу» (30.09.2026).
#
# Архив лежит в томе и переживает пересборку образа. Сбой архива не мешает
# запуску: сайт без старых файлов лучше, чем сайт, который не поднялся.

ARCHIVE=/app/static-archive
CURRENT=/app/.next/static
KEEP_DAYS=14

archive_static() {
  # Текущая сборка — в архив. Перезапись обновляет дату у файлов текущей
  # сборки, поэтому чистка ниже их не тронет.
  cp -R "$CURRENT/." "$ARCHIVE/" &&
    find "$ARCHIVE" -type f -mtime +"$KEEP_DAYS" -delete &&
    find "$ARCHIVE" -mindepth 1 -type d -empty -delete &&
    # Прошлые сборки — к текущей, не перезаписывая её файлы.
    cp -Rn "$ARCHIVE/." "$CURRENT/"
}

archive_static || echo "[entrypoint] архив статики не обновлён — старые файлы сборок недоступны" >&2

exec node server.js
